export const reviewedRules = Object.entries(groups).flatMap(([page, entries]) =>
  entries.map(([id, old, replacement]) => ({page, id, old, new: replacement, count: 1}))
);

export function normalizeReviewPath(pathname: string): string {
  return pathname.replace(/\/+$/, '').replace(/\.html$/, '').replace(/\/index$/, '') || '/';
}

export function applyReviewed(pathname: string, input: string) {
  const page = normalizeReviewPath(pathname);
  let html = input;
  const applied: string[] = [];
  const unmatched: string[] = [];
  for (const rule of reviewedRules) {
    if (rule.page !== page) continue;
    const count = html.split(rule.old).length - 1;
    if (count === rule.count) {
      html = html.split(rule.old).join(rule.new);
      applied.push(rule.id);
    } else if (count > 0 || (rule.new && !html.includes(rule.new))) {
      // A newer text or ambiguous occurrence must never be overwritten speculatively.
      unmatched.push(rule.id);
    }
  }
  return {html, applied, unmatched};
}
